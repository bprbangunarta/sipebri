use Illuminate\Support\Facades\Artisan;
use Illuminate\Support\Facades\Route;

/*
 * Docs and code must agree, and a machine checks it, not memory: every file, class, artisan command, environment variable, and URL named
 * in AGENTS.md (project part), CLAUDE.md, memory/PRD.md, .ai/rules, and the brief template must exist in the code. A missing one means
 * the doc is stale (or the code was removed without the doc). Matching what the code does is still the job of a person or agent on every
 * audit (AGENTS.md, step 4a).
 */

/**
 * @return array<string, string> doc file -> text that is checked
 */
function docTexts(): array
{
    $agents = (string) file_get_contents(base_path('AGENTS.md'));
    $boost = strpos($agents, '<laravel-boost-guidelines>');
    // Only the project part: the Boost block is generated by `php artisan boost:update` and names files of other projects.
    $texts = ['AGENTS.md' => $boost === false ? $agents : substr($agents, 0, $boost)];

    foreach (['CLAUDE.md', 'memory/PRD.md', 'docs/deployment.md', 'docs/briefs/TEMPLATE.md', ...array_map(fn (string $path): string => substr($path, strlen(base_path()) + 1), glob(base_path('.ai/rules/*.md')) ?: [])] as $file) {
        if (is_file(base_path($file))) {
            $texts[$file] = (string) preg_replace('/\A---.*?---\n/s', '', (string) file_get_contents(base_path($file)));
        }
    }

    return $texts;
}

/**
 * What a reference in a document names: a file, a class, an artisan command, a composer or npm script, an environment variable, a URL.
 */
function docReferenceKind(string $token): ?string
{
    return match (true) {
        // Each person's own settings, never committed (`.env.example` is the committed one).
        $token === '.env' => null,
        preg_match('#^(app|config|routes|resources|tests|database|scripts|docs|\.ai|\.githooks|\.github|memory|public|bootstrap|lang)/[\w./*{}\-\[\]|,]*(:\d+)?$#', $token) === 1 => 'path',
        preg_match('#^(\.[\w.\-]+|[\w\-]+\.(json|xml|neon|conf|yml|yaml|mjs|sh|steps))$#', $token) === 1 => 'path',
        preg_match('/^App\\\\[\w\\\\]+(::\w+)?(\(\))?$/', $token) === 1 => 'class',
        preg_match('/^php artisan [a-z][\w\-]*(:[\w\-]*)*(\s|$)/', $token) === 1 => 'command',
        preg_match('/^composer (run )?[a-z][\w\-]*(\s|$)/', $token) === 1 => 'composer',
        preg_match('/^npm run [\w:\-]+(\s|$)/', $token) === 1 => 'npm',
        preg_match('/^[A-Z][A-Z0-9_]{3,}$/', $token) === 1 && str_contains($token, '_') => 'env',
        preg_match('#^(GET |POST |PUT |DELETE |PATCH )?/[a-z][\w/{}\-.:?=&]*$#', $token) === 1 => 'route',
        default => null,
    };
}

/**
 * The references in one document: every backticked word, and every command line of a fenced block.
 *
 * @return list<array{0: string, 1: string, 2: string}> file, kind, reference
 */
function docReferencesIn(string $file, string $text): array
{
    $tokens = [];

    preg_match_all('/```[^\n]*\n(.*?)```/s', $text, $fences);

    foreach ($fences[1] as $block) {
        foreach (explode("\n", $block) as $line) {
            foreach (preg_split('/\s*&&\s*/', (string) preg_replace('/\s+#.*$/', '', trim($line))) ?: [] as $command) {
                $tokens[] = ltrim($command, '$ ');
            }
        }
    }

    preg_match_all('/`([^`\n]{2,160})`/', (string) preg_replace('/```.*?```/s', '', $text), $inline);

    $found = [];

    foreach (array_unique([...$tokens, ...$inline[1]]) as $token) {
        $token = trim($token);
        $kind = docReferenceKind($token);

        if ($kind !== null) {
            $found[] = [$file, $kind, $token];
        }
    }

    return $found;
}

/**
 * @return list<array{0: string, 1: string, 2: string}> file, kind, reference
 */
function docReferences(): array
{
    $found = [];

    foreach (docTexts() as $file => $text) {
        $found = [...$found, ...docReferencesIn($file, $text)];
    }

    return $found;
}

/**
 * References that are valid although they do not exist in this repository (created at run time, or owned by another system). Add only
 * with a reason.
 *
 * @return list<string>
 */
function docAllowlist(): array
{
    return [
        // Example name in the brief template; real briefs are created and deleted per piece of work.
        'docs/briefs/NNNN-short-title.md',
        // Laravel Boost's installer, named in the guide for a fresh clone; the project is already installed.
        'php artisan boost:install',
        // Registered by Laravel Boost (a dev package) outside the testing environment only.
        'php artisan boost:update',
        // A Claude Code slash command, not a URL of this application.
        '/infer-conventions',
        // Codex's own API, called by App\Auth\CodexAuthClient; not a route of this application.
        'POST /api/web-auth/password',
        // Codex's sign-in endpoint, named in docs/deployment.md next to CODEX_ENDPOINT; not a route of this application.
        '/api/web-auth',
        // Written by the Vite dev server while it runs; never committed.
        'public/hot',
        // File in the react-starter repository the UI rules were adopted from, named as their source.
        'docs/STANDARDS.md',
    ];
}

/**
 * `a/{b,c}/d` names two paths; `a/b|c|d` (folders side by side) names `a/b`, `a/c`, and `a/d`.
 *
 * @return list<string>
 */
function docPathAlternatives(string $path): array
{
    if (preg_match('/^(.*)\{([^{}]*,[^{}]*)\}(.*)$/', $path, $match) === 1) {
        return array_merge(...array_map(fn (string $option): array => docPathAlternatives($match[1].$option.$match[3]), explode(',', $match[2])));
    }

    if (str_contains($path, '|')) {
        $parent = dirname($path);

        return array_map(fn (string $name): string => $parent.'/'.$name, explode('|', basename($path)));
    }

    return [$path];
}

/**
 * @return list<string> the names of the files in the project's own folders
 */
function docProjectFileNames(): array
{
    static $names = null;

    if ($names !== null) {
        return $names;
    }

    $names = [];

    foreach (['app', 'config', 'database', 'docs', 'resources', 'routes', 'scripts', 'tests', '.ai', '.githooks', '.github', 'memory'] as $dir) {
        foreach (new RecursiveIteratorIterator(new RecursiveDirectoryIterator(base_path($dir), FilesystemIterator::SKIP_DOTS)) as $file) {
            $names[] = $file->getFilename();
        }
    }

    return array_values(array_unique($names));
}

function docPathExists(string $token): bool
{
    $path = rtrim(explode(':', $token)[0], '/');

    // `config/credit.max_survey_photos` is a config key: the file checked is config/credit.php and the key must be set.
    if (preg_match('#^config/([\w\-]+)\.(?!php$)([\w.]+)$#', $path, $config) === 1) {
        return is_file(base_path("config/{$config[1]}.php")) && config()->has("{$config[1]}.{$config[2]}");
    }

    // A bare file name (`verify.steps`) is a file of the project wherever it lives.
    if (! str_contains($path, '/') && ! file_exists(base_path($path))) {
        return in_array($path, docProjectFileNames(), true);
    }

    foreach (docPathAlternatives($path) as $alternative) {
        $exists = str_starts_with($alternative, 'storage/') // written at run time
            || file_exists(base_path($alternative))
            || glob(base_path($alternative)) !== []
            // `resources/js/routes` is generated by `php artisan wayfinder:generate` and not in git.
            || str_starts_with($alternative, 'resources/js/') && in_array(basename($alternative), ['routes', 'actions', 'wayfinder'], true);

        if (! $exists) {
            return false;
        }
    }

    return true;
}

/**
 * @param  list<string>  $routes
 */
function docRouteExists(string $token, array $routes): bool
{
    $named = array_values(array_filter(explode('/', trim(explode('?', (string) preg_replace('#^(GET|POST|PUT|DELETE|PATCH) #', '', $token))[0], '/')), fn (string $segment): bool => $segment !== ''));

    foreach ($routes as $route) {
        $segments = explode('/', trim($route, '/'));

        // The doc names the route or its leading part; a `{parameter}` on either side matches any segment on the other.
        if (count($named) <= count($segments) && array_filter($named, fn (string $segment, int $i): bool => ! docSegmentMatches($segment, $segments[$i]), ARRAY_FILTER_USE_BOTH) === []) {
            return true;
        }
    }

    return false;
}

function docSegmentMatches(string $named, string $route): bool
{
    return $named === $route || preg_match('/^\{[^}]*\}$/', $named) === 1 || preg_match('/^\{[^}]*\}$/', $route) === 1;
}

/**
 * `App\Support\Navigation::definition()` must exist as a method (or a constant or enum case when written without parentheses).
 */
function docClassExists(string $token): bool
{
    $class = (string) preg_replace('/(::\w+)?(\(\))?$/', '', $token);

    // A bare namespace such as `App\Support` names a folder under app/.
    $folder = app_path(str_replace('\\', '/', substr($class, 4)));

    if (! (class_exists($class) || interface_exists($class) || trait_exists($class) || enum_exists($class))) {
        return is_dir($folder) && ! str_contains($token, '::');
    }

    if (preg_match('/::(\w+)(\(\))?$/', $token, $member) !== 1) {
        return true;
    }

    return method_exists($class, $member[1]) || ($member[2] ?? '') === '' && defined("{$class}::{$member[1]}");
}

/**
 * `php artisan env:check --add`: the command must exist (`make:` names a family) and so must each long option written after it.
 */
function docCommandExists(string $token): bool
{
    preg_match('/^php artisan (\S+)(.*)$/', $token, $match);
    $commands = Artisan::all();

    if (str_ends_with($match[1], ':')) {
        return array_filter(array_keys($commands), fn (string $name): bool => str_starts_with($name, $match[1])) !== [];
    }

    if (! isset($commands[$match[1]])) {
        return false;
    }

    $command = $commands[$match[1]];
    $command->mergeApplicationDefinition();
    preg_match_all('/(?<=\s)--([\w\-]+)/', $match[2], $options);

    return array_filter($options[1], fn (string $option): bool => ! $command->getDefinition()->hasOption($option)) === [];
}

/**
 * `composer verify`, `composer run dev`, `npm run build`: the script must be in composer.json or package.json (Composer's own commands
 * are named in the list).
 */
function docScriptExists(string $kind, string $token): bool
{
    $words = explode(' ', $token);

    if ($kind === 'npm') {
        return isset(json_decode((string) file_get_contents(base_path('package.json')), true)['scripts'][$words[2]]);
    }

    $name = $words[1] === 'run' ? ($words[2] ?? '') : $words[1];
    $builtin = ['audit', 'show', 'install', 'update', 'require', 'remove', 'validate', 'outdated', 'dump-autoload', 'why', 'licenses', 'diagnose'];

    return isset(json_decode((string) file_get_contents(base_path('composer.json')), true)['scripts'][$name]) || ($words[1] !== 'run' && in_array($name, $builtin, true));
}

/**
 * The variable named as a whole word, in the places a variable is set or read (not in prose, not in the tests that name it).
 */
function docEnvExists(string $token): bool
{
    static $corpus = null;

    if ($corpus === null) {
        $corpus = '';

        foreach (['config', 'bootstrap', 'scripts', '.github', 'database', 'routes'] as $dir) {
            if (! is_dir(base_path($dir))) {
                continue;
            }

            foreach (new RecursiveIteratorIterator(new RecursiveDirectoryIterator(base_path($dir), FilesystemIterator::SKIP_DOTS)) as $file) {
                $corpus .= $file->isFile() && ! str_contains($file->getPathname(), '/bootstrap/cache/') ? (string) file_get_contents($file->getPathname()) : '';
            }
        }

        foreach (['.env.example', 'phpunit.xml', 'composer.json', 'package.json', 'vite.config.ts', 'devcore.conf'] as $file) {
            $corpus .= is_file(base_path($file)) ? (string) file_get_contents(base_path($file)) : '';
        }
    }

    return preg_match('/(?<![A-Z0-9_])'.preg_quote($token, '/').'(?![A-Z0-9_])/', $corpus) === 1;
}

/**
 * @param  list<string>  $routes
 */
function docReferenceExists(string $kind, string $token, array $routes): bool
{
    return match ($kind) {
        'path' => docPathExists($token),
        'class' => docClassExists($token),
        'command' => docCommandExists($token),
        'composer', 'npm' => docScriptExists($kind, $token),
        'env' => docEnvExists($token),
        'route' => docRouteExists($token, $routes),
    };
}

/**
 * @return list<string> the routes of the application, without a leading slash
 */
function docRoutes(): array
{
    return array_map(fn ($route): string => $route->uri(), Route::getRoutes()->getRoutes());
}

it('names in the docs only files, classes, commands, variables, and URLs that exist in the code', function () {
    $routes = docRoutes();
    $missing = [];

    foreach (docReferences() as [$file, $kind, $token]) {
        if (! in_array($token, docAllowlist(), true) && ! docReferenceExists($kind, $token, $routes)) {
            $missing[] = "{$file}: {$kind} {$token}";
        }
    }

    expect($missing)->toBe([]);
});

it('keeps every allowlist entry in use: one that no document names any more is removed', function () {
    $named = array_map(fn (array $reference): string => $reference[2], docReferences());

    expect(array_values(array_diff(docAllowlist(), $named)))->toBe([], 'Allowlist entry that no document names: remove it from docAllowlist().');
});

it('does not allow a reference that does exist: an entry that is no longer needed is removed', function () {
    $routes = docRoutes();
    $needless = array_values(array_filter(docAllowlist(), function (string $token) use ($routes): bool {
        $kind = docReferenceKind($token);

        return $kind !== null && docReferenceExists($kind, $token, $routes);
    }));

    expect($needless)->toBe([], 'Allowlist entry that the code already satisfies: remove it from docAllowlist().');
});

it('finds each kind of reference in a document, in prose and in a fenced block', function () {
    $text = "See `app/Support/Navigation.php` and `App\\Support\\Navigation::for()`.\n\n```bash\ncomposer setup && php artisan migrate --force   # idempotent\n```\n\nSet `APP_KEY`; open `/loan-applications`; run `npm run build`.\n";
    $kinds = array_map(fn (array $reference): string => $reference[1].' '.$reference[2], docReferencesIn('x.md', $text));

    expect($kinds)->toContain('path app/Support/Navigation.php', 'class App\\Support\\Navigation::for()', 'composer composer setup', 'command php artisan migrate --force', 'env APP_KEY', 'route /loan-applications', 'npm npm run build');
});

it('reports every kind of reference that does not exist, and accepts the ones that do', function (string $token, bool $exists) {
